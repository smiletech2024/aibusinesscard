export async function POST(req: NextRequest) {
  try {
    const { messages, sessionKey } = await req.json()
    if (!messages || !Array.isArray(messages)) {
      return new Response('Bad Request', { status: 400 })
    }

    const admin = getAdmin()

    // セッション upsert & ユーザーメッセージ保存
    if (sessionKey) {
      const lastMsg = messages[messages.length - 1]
      if (lastMsg?.role === 'user') {
        await admin.from('support_sessions').upsert(
          { session_key: sessionKey, updated_at: new Date().toISOString() },
          { onConflict: 'session_key' }
        )
        await admin.from('support_messages').insert({
          session_key: sessionKey,
          role: 'user',
          content: lastMsg.content,
        })
      }
    }

    // 運営対応中はAI応答をスキップ
    if (sessionKey) {
      const { data: session } = await admin
        .from('support_sessions')
        .select('operator_active')
        .eq('session_key', sessionKey)
        .single()

      if (session?.operator_active) {
        // ユーザーメッセージは保存済み、AI応答なし
        return new Response('', {
          headers: { 'Content-Type': 'text/plain; charset=utf-8' },
        })
      }
    }

    const stream = await deepseek.chat.completions.create({
      model: MODEL,
      messages: [
        { role: 'system', content: SYSTEM_PROMPT },
        ...messages.slice(-10),
      ],
      stream: true,
      max_tokens: 600,
      temperature: 0.6,
    })

    const encoder = new TextEncoder()
    let rawResponse = ''

    // ① ストリームを全文収集
    for await (const chunk of stream) {
      rawResponse += chunk.choices[0]?.delta?.content ?? ''
    }

    // ② 「ペルソナ」を強制置換（AIが指示を無視しても確実に除去）
    const cleanedResponse = rawResponse
      .replace(/ペルソナ編集/g, '「AIを強化」')
      .replace(/ペルソナ設定/g, 'AI設定')
      .replace(/ペルソナ/g, 'AI設定')

    // ③ DB保存（置換済みテキストで保存）
    if (sessionKey && cleanedResponse) {
      await admin.from('support_messages').insert({
        session_key: sessionKey,
        role: 'assistant',
        content: cleanedResponse,
      })
      await admin.from('support_sessions').upsert(
        { session_key: sessionKey, updated_at: new Date().toISOString() },
        { onConflict: 'session_key' }
      )
    }

    // ④ クライアントへ送信
    const readable = new ReadableStream({
      start(controller) {
        controller.enqueue(encoder.encode(cleanedResponse))
        controller.close()
      },
    })

    return new Response(readable, {
      headers: {
        'Content-Type': 'text/plain; charset=utf-8',
        'Cache-Control': 'no-cache',
        'X-Accel-Buffering': 'no',
      },
    })
  } catch (err) {
    console.error('[support-chat]', err)
    return new Response('Internal Server Error', { status: 500 })
  }
}
